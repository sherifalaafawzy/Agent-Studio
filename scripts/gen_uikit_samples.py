"""Write frontend/lib/uikit/samples.generated.ts from backend/app/uikit/samples.py (one example for every component type).

    python scripts/gen_uikit_samples.py          # update the file
    python scripts/gen_uikit_samples.py --check  # exit 1 when it is out of date (a backend test runs this check)
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
OUT = ROOT / "frontend" / "lib" / "uikit" / "samples.generated.ts"


def render() -> str:
    from app.uikit.kinds import KINDS
    from app.uikit.samples import SAMPLES
    kinds = [{"type": k.type, "group": k.group, "about": k.about, "need": [list(g) for g in k.need]} for k in KINDS.values()]
    return ("// Generated by scripts/gen_uikit_samples.py from backend/app/uikit/samples.py. Do not edit: run the script.\n"
            f"export const SAMPLES: Record<string, any> = {json.dumps(SAMPLES, indent=1, ensure_ascii=False)};\n\n"
            f"export const KIND_LIST: { '{ type: string; group: string; about: string; need: string[][] }[]' } = {json.dumps(kinds, indent=1, ensure_ascii=False)};\n")


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text(encoding="utf-8") == text else 1)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(text)} bytes)")
